-- 3. CREACIÓN DE TABLAS
-- =============================================================================

-- 1. Tabla de Personas (Base para Clientes y Vendedores)
CREATE TABLE TBL_PERSONA (
    PER_ID          NUMBER          PRIMARY KEY,
    PER_NOMBRE      VARCHAR2(100)   NOT NULL,
    PER_APELLIDO    VARCHAR2(100)   NOT NULL,
    PER_DIRECCION   VARCHAR2(200),
    PER_TELEFONO    VARCHAR2(50),
    PER_EMAIL       VARCHAR2(100)
);

-- 2. Tabla de Clientes
CREATE TABLE TBL_CLIENTE (
    CLI_ID          NUMBER          GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PER_ID          NUMBER          NOT NULL UNIQUE,
    CONSTRAINT FK_CLIENTE_PERSONA FOREIGN KEY (PER_ID) REFERENCES TBL_PERSONA(PER_ID) ON DELETE CASCADE
);

-- 3. Tabla de Vendedores
CREATE TABLE TBL_VENDEDOR (
    VEN_ID          NUMBER          GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PER_ID          NUMBER          NOT NULL UNIQUE,
    CONSTRAINT FK_VENDEDOR_PERSONA FOREIGN KEY (PER_ID) REFERENCES TBL_PERSONA(PER_ID) ON DELETE CASCADE
);

-- 4. Tabla de Productos
CREATE TABLE TBL_PRODUCTO (
    PRO_ID          NUMBER          PRIMARY KEY,
    PRO_NOMBRE      VARCHAR2(150)   NOT NULL,
    PRO_PRECIO      NUMBER(12,2)    NOT NULL,
    PRO_STOCK       NUMBER          NOT NULL,
    PRO_DESCRIPCION VARCHAR2(500)
);

-- 5. Tabla de Proveedores
CREATE TABLE TBL_PROVEEDOR (
    PRO_ID          NUMBER          PRIMARY KEY,
    PRO_NOMBRE      VARCHAR2(150)   NOT NULL,
    PRO_CONTACTO    VARCHAR2(100),
    PRO_TELEFONO    VARCHAR2(50)
);

-- 6. Tabla de Promociones
CREATE TABLE TBL_PROMOCION (
    PRM_ID          NUMBER          PRIMARY KEY,
    PRM_DESCRIPCION VARCHAR2(255)   NOT NULL,
    PRM_DESCUENTO   NUMBER(5,2)     NOT NULL,
    PRM_FECHA_INI   DATE            NOT NULL,
    PRM_FECHA_FIN   DATE            NOT NULL
);

-- 7. Tabla de Pagos
CREATE TABLE TBL_PAGO (
    PAG_ID          NUMBER          PRIMARY KEY,
    PAG_METODO      VARCHAR2(50)    NOT NULL,
    PAG_FECHA       DATE            DEFAULT SYSDATE,
    PAG_MONTO       NUMBER(12,2)    NOT NULL
);

-- 8. Tabla de Facturas
CREATE TABLE TBL_FACTURA (
    FAC_NUM_FACTURA NUMBER          PRIMARY KEY,
    FAC_FECHA       DATE            DEFAULT SYSDATE NOT NULL,
    FAC_SUBTOTAL    NUMBER(12,2)    NOT NULL,
    FAC_IVA         NUMBER(12,2)    NOT NULL,
    FAC_TOTAL       NUMBER(12,2)    NOT NULL,
    CLI_ID          NUMBER          NOT NULL,
    VEN_ID          NUMBER          NOT NULL,
    PAG_ID          NUMBER,
    CONSTRAINT FK_FACTURA_CLIENTE  FOREIGN KEY (CLI_ID) REFERENCES TBL_CLIENTE(CLI_ID),
    CONSTRAINT FK_FACTURA_VENDEDOR FOREIGN KEY (VEN_ID) REFERENCES TBL_VENDEDOR(VEN_ID),
    CONSTRAINT FK_FACTURA_PAGO     FOREIGN KEY (PAG_ID) REFERENCES TBL_PAGO(PAG_ID)
);

-- 9. Tabla de Reclamos
CREATE TABLE TBL_RECLAMO (
    REC_ID_RECLAMO  NUMBER          PRIMARY KEY,
    FAC_NUM_FACTURA NUMBER          NOT NULL,
    REC_FECHA       DATE            DEFAULT SYSDATE NOT NULL,
    REC_DESCRIPCION VARCHAR2(1000)  NOT NULL,
    REC_ESTADO      VARCHAR2(50)    DEFAULT 'Pendiente' NOT NULL,
    CONSTRAINT FK_RECLAMO_FACTURA FOREIGN KEY (FAC_NUM_FACTURA) REFERENCES TBL_FACTURA(FAC_NUM_FACTURA) ON DELETE CASCADE
);

-- 10. Tabla de Reintegros
CREATE TABLE TBL_REINTEGRO (
    REI_ID          NUMBER          PRIMARY KEY,
    REC_ID_RECLAMO  NUMBER          NOT NULL,
    REI_FECHA       DATE            DEFAULT SYSDATE NOT NULL,
    REI_MONTO       NUMBER(12,2)    NOT NULL,
    REI_MOTIVO      VARCHAR2(500),
    CONSTRAINT FK_REINTEGRO_RECLAMO FOREIGN KEY (REC_ID_RECLAMO) REFERENCES TBL_RECLAMO(REC_ID_RECLAMO) ON DELETE CASCADE
);

-- =============================================================================
-- TABLAS INTERMEDIAS Y DE DETALLE
-- =============================================================================

-- Proveedor - Producto
CREATE TABLE PROVEE_PRODUC (
    PROV_ID         NUMBER          NOT NULL,
    PRO_ID          NUMBER          NOT NULL,
    PRIMARY KEY (PROV_ID, PRO_ID),
    CONSTRAINT FK_PROVPROD_PROVEEDOR FOREIGN KEY (PROV_ID) REFERENCES TBL_PROVEEDOR(PRO_ID) ON DELETE CASCADE,
    CONSTRAINT FK_PROVPROD_PRODUCTO  FOREIGN KEY (PRO_ID)  REFERENCES TBL_PRODUCTO(PRO_ID)  ON DELETE CASCADE
);

-- Promoción - Producto
CREATE TABLE PROMO_PRODU (
    PRM_ID          NUMBER          NOT NULL,
    PRO_ID          NUMBER          NOT NULL,
    PRIMARY KEY (PRM_ID, PRO_ID),
    CONSTRAINT FK_PROMPROD_PROMOCION FOREIGN KEY (PRM_ID) REFERENCES TBL_PROMOCION(PRM_ID) ON DELETE CASCADE,
    CONSTRAINT FK_PROMPROD_PRODUCTO  FOREIGN KEY (PRO_ID) REFERENCES TBL_PRODUCTO(PRO_ID)  ON DELETE CASCADE
);

-- Detalle Factura - Producto
CREATE TABLE FACTU_PRODUC (
    FAC_NUM_FACTURA NUMBER          NOT NULL,
    PRO_ID          NUMBER          NOT NULL,
    CANTIDAD        NUMBER          NOT NULL,
    PRECIO_UNITARIO NUMBER(12,2)    NOT NULL,
    SUBTOTAL_LINEA  NUMBER(12,2)    NOT NULL,
    PRIMARY KEY (FAC_NUM_FACTURA, PRO_ID),
    CONSTRAINT FK_FACTPROD_FACTURA  FOREIGN KEY (FAC_NUM_FACTURA) REFERENCES TBL_FACTURA(FAC_NUM_FACTURA) ON DELETE CASCADE,
    CONSTRAINT FK_FACTPROD_PRODUCTO FOREIGN KEY (PRO_ID)          REFERENCES TBL_PRODUCTO(PRO_ID)
);

